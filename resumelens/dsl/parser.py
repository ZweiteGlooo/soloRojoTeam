"""Load and validate candidate profiles with the textX grammar.

Three kinds of errors are rejected:

  * lexical   - a token does not match its terminal (e.g. a malformed email,
                a skill written in lowercase)
  * syntactic - tokens in the wrong place or missing (no skills section,
                unknown profile key, ACCEPTED without the recognized word)
  * semantic  - well formed but inconsistent (a profile reported twice,
                duplicated skills, an accepted word using skills the candidate
                does not have, 0 years of experience)

The first two come from the parser generated by textX from candidate.tx; the
last one from the object processors registered below.
"""
from pathlib import Path

from textx import TextXSemanticError, TextXSyntaxError, metamodel_from_file

GRAMMAR = Path(__file__).with_name("candidate.tx")


class ProfileError(Exception):
    """A candidate profile that violates the lexical, syntactic or semantic rules."""

    def __init__(self, kind, message, line=None, col=None):
        self.kind, self.line, self.col = kind, line, col
        where = f" (line {line}, col {col})" if line else ""
        super().__init__(f"{kind} error{where}: {message}")


def _check_job(job):
    if job.years <= 0:
        raise TextXSemanticError(f"years of experience must be positive, got {job.years}")


def _check_skills(skills):
    seen = set()
    for skill in skills.items:
        if skill in seen:
            raise TextXSemanticError(f"skill {skill} is listed twice")
        seen.add(skill)


def _check_profile(model):
    reported = set()
    for result in model.profiles.results:
        if result.profile in reported:
            raise TextXSemanticError(f"profile {result.profile} is reported twice")
        reported.add(result.profile)
        unknown = [s for s in result.word if s not in model.skills.items]
        if unknown:
            raise TextXSemanticError(
                f"{result.profile} was accepted with skills not in the skills section: {', '.join(unknown)}")


_METAMODEL = None


def metamodel():
    global _METAMODEL
    if _METAMODEL is None:
        _METAMODEL = metamodel_from_file(str(GRAMMAR))
        _METAMODEL.register_obj_processors({
            "Job": _check_job,
            "Skills": _check_skills,
            "CandidateProfile": _check_profile,
        })
    return _METAMODEL


def _syntax_kind(err):
    # textX reports both cases as syntax errors; when the parser was expecting
    # one of our regex terminals the token itself is malformed (lexical error)
    msg = str(err)
    return "lexical" if any(t in msg for t in ("Email", "Phone", "Url", "Skill", "BlockName")) else "syntax"


def parse(text):
    """Parse and validate a profile. Returns the textX model or raises ProfileError."""
    try:
        return metamodel().model_from_str(text)
    except TextXSyntaxError as err:
        raise ProfileError(_syntax_kind(err), err.message, err.line, err.col) from err
    except TextXSemanticError as err:
        raise ProfileError("semantic", err.message, err.line, err.col) from err


def parse_file(path):
    return parse(Path(path).read_text(encoding="utf-8"))


def validate(text):
    """(True, None) for a valid profile, (False, message) otherwise."""
    try:
        parse(text)
        return True, None
    except ProfileError as err:
        return False, str(err)
