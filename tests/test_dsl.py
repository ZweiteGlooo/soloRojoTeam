"""Tests for the dsl stage."""
from pathlib import Path

import pytest

from resumelens.dsl.generator import to_dsl
from resumelens.dsl.parser import ProfileError, parse, parse_file, validate
from resumelens.extraction import extract_file
from resumelens.normalization import normalize_skills_safe
from resumelens.recognition import recognize_all

EXAMPLES = Path("resumelens/dsl/examples")
VALID = sorted((EXAMPLES / "valid").glob("*.rlp"))
INVALID = sorted((EXAMPLES / "invalid").glob("*.rlp"))

MINIMAL = """candidate "Wednesday Addams" {
    skills { JAVASCRIPT, REACT, NODE_JS, POSTGRESQL, GIT }
    profiles {
        FULL_STACK_DEVELOPER: ACCEPTED [JAVASCRIPT, REACT, NODE_JS, POSTGRESQL, GIT]
    }
}
"""

FULL = """candidate "Peter Benjamin Parker" {
    contact {
        email peter.parker@dailybugle.com
        phone +57 300 123 4567
        linkedin linkedin.com/in/peterparker
        github https://github.com/spidey-dev
    }
    education {
        degree "B.Sc." in "Software Engineering"
        degree "Master's"
    }
    experience {
        4 years "backend developer"
        1 year "intern"
    }
    skills { JAVA, SPRING_BOOT, REST, MYSQL, GIT }
    profiles {
        BACKEND_DEVELOPER: ACCEPTED [JAVA, SPRING_BOOT, REST, MYSQL, GIT]
        DATA_ENGINEER: REJECTED missing [PROCESSING]
        FULL_STACK_DEVELOPER: REJECTED
    }
}
"""


def error_kind(text):
    with pytest.raises(ProfileError) as info:
        parse(text)
    return info.value.kind


class TestValidProfiles:
    def test_minimal(self):
        model = parse(MINIMAL)
        assert model.name == "Wednesday Addams"
        assert model.contact is None and model.education is None and model.experience is None
        assert model.skills.items == ["JAVASCRIPT", "REACT", "NODE_JS", "POSTGRESQL", "GIT"]

    def test_full_profile_structure(self):
        model = parse(FULL)
        assert [(i.kind, i.value) for i in model.contact.items] == [
            ("email", "peter.parker@dailybugle.com"), ("phone", "+57 300 123 4567"),
            ("linkedin", "linkedin.com/in/peterparker"), ("github", "https://github.com/spidey-dev")]
        assert [(d.title, d.field) for d in model.education.records] == \
            [("B.Sc.", "Software Engineering"), ("Master's", "")]
        assert [(j.years, j.description) for j in model.experience.jobs] == \
            [(4, "backend developer"), (1, "intern")]

    def test_results(self):
        results = parse(FULL).profiles.results
        assert [(r.profile, r.status) for r in results] == [
            ("BACKEND_DEVELOPER", "ACCEPTED"), ("DATA_ENGINEER", "REJECTED"), ("FULL_STACK_DEVELOPER", "REJECTED")]
        assert results[0].word == ["JAVA", "SPRING_BOOT", "REST", "MYSQL", "GIT"]
        assert results[1].missing == ["PROCESSING"]

    def test_empty_skills_section_is_allowed(self):
        assert validate('candidate "X" { skills { } profiles { DATA_ENGINEER: REJECTED } }')[0]

    def test_comments_are_ignored(self):
        assert validate("// generated by ResumeLens\n" + MINIMAL)[0]

    def test_whitespace_is_not_significant(self):
        assert validate(" ".join(MINIMAL.split()))[0]

    @pytest.mark.parametrize("path", VALID, ids=lambda p: p.stem)
    def test_valid_examples(self, path):
        parse_file(path)


class TestLexicalErrors:
    def test_bad_email(self):
        assert error_kind(MINIMAL.replace("skills", "contact { email wednesday@ }\n    skills")) == "lexical"

    def test_bad_phone(self):
        assert error_kind(MINIMAL.replace("skills", "contact { phone 12 }\n    skills")) == "lexical"

    def test_link_must_be_linkedin_or_github(self):
        assert error_kind(MINIMAL.replace("skills", "contact { linkedin example.com/me }\n    skills")) == "lexical"

    def test_lowercase_skill(self):
        assert error_kind(MINIMAL.replace("REACT, NODE_JS", "react, NODE_JS")) == "lexical"


class TestSyntaxErrors:
    def test_missing_skills(self):
        assert error_kind(MINIMAL.replace("    skills { JAVASCRIPT, REACT, NODE_JS, POSTGRESQL, GIT }\n", "")) == "syntax"

    def test_unknown_profile(self):
        assert error_kind(MINIMAL.replace("FULL_STACK_DEVELOPER", "WEB_DESIGNER")) == "syntax"

    def test_accepted_without_word(self):
        assert error_kind(MINIMAL.replace(" [JAVASCRIPT, REACT, NODE_JS, POSTGRESQL, GIT]\n    }", "\n    }")) == "syntax"

    def test_unknown_status(self):
        assert error_kind(MINIMAL.replace("ACCEPTED", "MAYBE")) == "syntax"

    def test_profiles_before_skills(self):
        text = MINIMAL.replace("{\n    skills", "{\n    profiles { DATA_ENGINEER: REJECTED }\n    skills")
        assert error_kind(text) == "syntax"

    def test_unclosed_brace(self):
        assert error_kind(MINIMAL.rstrip()[:-1]) == "syntax"

    def test_error_has_position(self):
        with pytest.raises(ProfileError) as info:
            parse(MINIMAL.replace("ACCEPTED", "MAYBE"))
        assert info.value.line == 4


class TestSemanticErrors:
    def test_duplicate_profile(self):
        text = MINIMAL.replace("    }\n}", "        FULL_STACK_DEVELOPER: REJECTED\n    }\n}")
        assert error_kind(text) == "semantic"

    def test_duplicate_skill(self):
        assert error_kind(MINIMAL.replace("GIT }", "GIT, GIT }")) == "semantic"

    def test_word_not_in_skills(self):
        assert error_kind(MINIMAL.replace("[JAVASCRIPT, REACT", "[TYPESCRIPT, REACT")) == "semantic"

    def test_zero_years(self):
        assert error_kind(MINIMAL.replace("skills", "experience { 0 years \"web\" }\n    skills")) == "semantic"


@pytest.mark.parametrize("path", INVALID, ids=lambda p: p.stem)
def test_invalid_examples_fail_with_the_kind_in_their_name(path):
    with pytest.raises(ProfileError) as info:
        parse_file(path)
    assert info.value.kind == path.stem.split("_")[0]


class TestGenerator:
    @staticmethod
    def generate(name):
        extracted = extract_file(f"data/resumes/{name}.txt")
        normalized, _ = normalize_skills_safe(extracted["raw_skills"])
        return to_dsl(extracted, normalized, recognize_all(normalized))

    @pytest.mark.parametrize("name", ["wednesday_addams", "mary_jane_watson", "peter_parker"])
    def test_generated_profiles_are_valid(self, name):
        ok, error = validate(self.generate(name))
        assert ok, error

    def test_generated_matches_committed_example(self):
        assert self.generate("wednesday_addams") == (EXAMPLES / "valid" / "wednesday_addams.rlp").read_text(encoding="utf-8")

    def test_generated_reports_four_profiles(self):
        model = parse(self.generate("peter_parker"))
        assert len(model.profiles.results) == 4
        accepted = [r.profile for r in model.profiles.results if r.status == "ACCEPTED"]
        assert accepted == ["FULL_STACK_DEVELOPER", "BACKEND_DEVELOPER"]

    def test_quotes_in_text_do_not_break_the_profile(self):
        extracted = {"name": 'Ana "La Dev" Ruiz', "experience": [{"years": 2, "description": 'built "apps"'}]}
        assert validate(to_dsl(extracted, [], recognize_all([])))[0]

    def test_no_name(self):
        assert parse(to_dsl({"name": None}, [], recognize_all([]))).name == "Unknown candidate"
